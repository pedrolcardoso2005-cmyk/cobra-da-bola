import { DatabaseSync } from "node:sqlite";
import { mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DB_PATH = process.env.DB_PATH ?? `${__dirname}/../../data/cobra.db`;
mkdirSync(dirname(DB_PATH), { recursive: true });

export const db = new DatabaseSync(DB_PATH);
db.exec("PRAGMA journal_mode = WAL;");
db.exec("PRAGMA foreign_keys = ON;");

db.exec(`
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  display_name TEXT NOT NULL,
  avatar_url TEXT,
  created_at INTEGER NOT NULL,
  rating_overall INTEGER NOT NULL DEFAULT 1000,
  rating_season INTEGER NOT NULL DEFAULT 1000,
  season_id TEXT NOT NULL DEFAULT 'S1',
  matches_played INTEGER NOT NULL DEFAULT 0,
  matches_won INTEGER NOT NULL DEFAULT 0,
  matches_lost INTEGER NOT NULL DEFAULT 0,
  win_streak INTEGER NOT NULL DEFAULT 0,
  best_win_streak INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS password_resets (
  token TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at INTEGER NOT NULL,
  used INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS matches (
  id TEXT PRIMARY KEY,
  code TEXT NOT NULL,
  kind TEXT NOT NULL,
  participant_count INTEGER NOT NULL,
  started_at INTEGER NOT NULL,
  finished_at INTEGER,
  winner_user_id TEXT REFERENCES users(id),
  runner_up_user_id TEXT REFERENCES users(id),
  state_json TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS match_participants (
  match_id TEXT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  team TEXT,
  final_position INTEGER,
  correct_answers INTEGER NOT NULL DEFAULT 0,
  wrong_answers INTEGER NOT NULL DEFAULT 0,
  rating_delta INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (match_id, user_id)
);

CREATE TABLE IF NOT EXISTS questions (
  id TEXT PRIMARY KEY,
  category TEXT NOT NULL,
  difficulty TEXT NOT NULL,
  format TEXT NOT NULL,
  prompt TEXT NOT NULL,
  choices_json TEXT,
  correct_answer TEXT NOT NULL,
  accepted_answers_json TEXT,
  created_by_user_id TEXT,
  created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS career_questions (
  id TEXT PRIMARY KEY,
  clubs_json TEXT NOT NULL,
  player_name TEXT NOT NULL,
  accepted_answers_json TEXT,
  created_at INTEGER NOT NULL
);
`);

// Additive migration: adds columns the question bank needs (explanation,
// source, season reference) without touching existing rows/tables.
const questionCols = (db.prepare("PRAGMA table_info(questions)").all() as unknown as { name: string }[]).map((c) => c.name);
for (const [col, ddl] of [
  ["explanation", "ALTER TABLE questions ADD COLUMN explanation TEXT"],
  ["source_url", "ALTER TABLE questions ADD COLUMN source_url TEXT"],
  ["season_ref", "ALTER TABLE questions ADD COLUMN season_ref TEXT"],
  // 'approved': usable by the game (every pre-existing row defaults here).
  // 'pending_review': generated by the AI pipeline, awaiting admin approval.
  // 'rejected': kept for audit/dedupe history, never served to the game.
  ["status", "ALTER TABLE questions ADD COLUMN status TEXT NOT NULL DEFAULT 'approved'"],
  ["generated_by", "ALTER TABLE questions ADD COLUMN generated_by TEXT"],
] as const) {
  if (!questionCols.includes(col)) db.exec(ddl);
}

// Additive migration: same idiom as the questions table above, for the
// Desafio das Carreiras metadata (theme/difficulty/source/season/status).
// NULL theme/difficulty on existing rows means "any" when filtering --
// same "unset = aleatorio" convention already used for question filters.
const careerCols = (db.prepare("PRAGMA table_info(career_questions)").all() as unknown as { name: string }[]).map((c) => c.name);
for (const [col, ddl] of [
  ["theme", "ALTER TABLE career_questions ADD COLUMN theme TEXT"],
  ["difficulty", "ALTER TABLE career_questions ADD COLUMN difficulty TEXT"],
  ["source_url", "ALTER TABLE career_questions ADD COLUMN source_url TEXT"],
  ["season_ref", "ALTER TABLE career_questions ADD COLUMN season_ref TEXT"],
  ["status", "ALTER TABLE career_questions ADD COLUMN status TEXT NOT NULL DEFAULT 'approved'"],
] as const) {
  if (!careerCols.includes(col)) db.exec(ddl);
}

// AI-generated question pipeline: embeddings for semantic dedupe, and a log
// of each generation batch for auditing/cost tracking. Both are additive and
// unused by the existing game/question-CRUD flow.
db.exec(`
CREATE TABLE IF NOT EXISTS question_embeddings (
  question_id TEXT PRIMARY KEY REFERENCES questions(id) ON DELETE CASCADE,
  model TEXT NOT NULL,
  embedding BLOB NOT NULL,
  created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS ai_generation_log (
  id TEXT PRIMARY KEY,
  category TEXT NOT NULL,
  difficulty TEXT NOT NULL,
  requested INTEGER NOT NULL,
  generated INTEGER NOT NULL,
  rejected_validation INTEGER NOT NULL,
  rejected_duplicate INTEGER NOT NULL,
  flagged_for_review INTEGER NOT NULL,
  auto_approved INTEGER NOT NULL,
  model TEXT NOT NULL,
  error TEXT,
  started_at INTEGER NOT NULL,
  finished_at INTEGER NOT NULL
);
`);

// Meu Historico (Modo Solo): one row per graded/skipped answer, server-side
// only (every row is written from an authenticated request already judged
// by the server, never trusted from the client). session_id is a client-
// generated grouping key for a single "partida" (regenerated each time the
// player presses Comecar/Reiniciar) -- used only to group rows for
// per-match stats and "melhor pontuacao", never validated, so it can't be
// used to forge a correct/wrong/skipped tally.
db.exec(`
CREATE TABLE IF NOT EXISTS solo_answer_log (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  session_id TEXT NOT NULL,
  result TEXT NOT NULL,
  at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_solo_answer_log_user ON solo_answer_log(user_id, kind);
CREATE INDEX IF NOT EXISTS idx_solo_answer_log_session ON solo_answer_log(user_id, kind, session_id);
`);
